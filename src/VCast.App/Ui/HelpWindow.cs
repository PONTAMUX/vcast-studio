    static void Section(Panel body, string title, IEnumerable<(string Term, string Text)> rows)
    {
        body.Children.Add(new TextBlock { Text = title, FontSize = 16, FontWeight = FontWeights.SemiBold, Margin = new Thickness(0, 14, 0, 6) });
        foreach (var (term, text) in rows)
        {
            var tb = new TextBlock { TextWrapping = TextWrapping.Wrap, Margin = new Thickness(0, 3, 0, 3) };
            tb.Inlines.Add(new Run(term) { FontWeight = FontWeights.SemiBold, Foreground = Theme.Fg });
            tb.Inlines.Add(new Run("　" + text) { Foreground = Theme.Sub });
            body.Children.Add(tb);
        }
    }
